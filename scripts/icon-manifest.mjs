// Lists which sizes exist for every icon in public/icons/{16,32,48}, so the UI never has to scale one.
// Run after adding or removing icon files: node scripts/icon-manifest.mjs
import { readdirSync, writeFileSync, readFileSync } from 'node:fs'

const sizes = [16, 32, 48]
const have = {}
for (const s of sizes) {
  for (const f of readdirSync(`public/icons/${s}`)) {
    if (!f.endsWith('.png')) continue
    const name = f.slice(0, -4)
    const png = readFileSync(`public/icons/${s}/${f}`)
    const w = png.readUInt32BE(16)
    const h = png.readUInt32BE(20)
    if (w !== s || h !== s) throw new Error(`public/icons/${s}/${f} is ${w}x${h}, expected ${s}x${s}`)
    ;(have[name] ??= []).push(s)
  }
}
const lines = Object.keys(have)
  .sort()
  .map((n) => `  ${n}: [${have[n].join(', ')}],`)
writeFileSync(
  'src/ui/iconManifest.ts',
  `// Generated by scripts/icon-manifest.mjs. Do not edit.\nexport const ICON_SIZES: Record<string, number[]> = {\n${lines.join('\n')}\n}\n`,
)
console.log(`${lines.length} icons`)
